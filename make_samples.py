"""Writes outputs/evidence/sample_outputs.md: five real complaints with the drafts they produced, plus the
appended doc entry and email draft for one approved ticket (written to a separate folder, not the live log)."""
import config, mcp_layer as mcp, eval_set
from desk import Desk

PICK = ["R1497", "R3277", "R484", "R1547", "R3885"]      # covered+recurring, covered+one-off, not covered+recurring, HOLD, not covered
EV = config.OUT / "evidence"; SAMPLE_DIR = EV / "sample_mcp"

desk = Desk()
rows = {s["id"]: s for s in eval_set.sample_complaints()}
out = ["# Five sample complaints and the drafts they produced",
       "Real 1-2 star reviews from the Milestone 2 CSV (personal data removed at the input gate). Generated by `make_samples.py`.\n"]
approved = None
for i, rid in enumerate(PICK, 1):
    t = desk.submit(rows[rid]["text"], session_id="samples")
    f, p, c, d = t["outputs"]["facts"], t["outputs"]["pattern"], t["outputs"]["compliance"], t["draft"]
    out += [f"## {i}. {rid} ({rows[rid]['rating']}★)", f"**Complaint:** {t['message']}\n",
            f"- **Facts:** {f['status']}" + (f" -> {f['citation_url']}" if f['status'] == 'covered' else f" (searched: {'; '.join(f['searched'])})"),
            f"- **Pattern:** {p['trend']}, {p['similar_count']} similar reviews in {p['window']['days']} days ({p['recent_count']} recent / {p['prior_count']} prior), theme '{p['theme']}'",
            f"- **Compliance:** {c['incoming_status']}; advice asked: {c['advice_requested']}",
            f"- **Reviewer:** {'passed' if t['review']['passed'] else 'FAILED'}",
            f"- **Agents fired:** {', '.join(t['fired_log'][0]['agents_fired'])}\n",
            "**Reply draft:**", "", "> " + d["reply"]["full_text"].replace("\n", "\n> "), "",
            f"**Routing note:** {d['routing']['note']}\n"]
    if rid == "R3277":
        approved = t

# approve one ticket and show exactly what the MCP step writes (into evidence/sample_mcp, not the live log)
SAMPLE_DIR.mkdir(parents=True, exist_ok=True)
for fn in SAMPLE_DIR.glob("*"): fn.unlink()
mcp.OUT = SAMPLE_DIR
gate = mcp.ApprovalGate("sample"); gate.decide(True)
rec, email = mcp.build_payloads(approved)
mcp.call_tool("append_support_record", rec, gate); mcp.call_tool("create_email_draft", email, gate)
out += ["## Appended doc entry (after a human approved ticket 2)", "```markdown", (SAMPLE_DIR / "support_log.md").read_text(encoding="utf-8").strip(), "```\n",
        "## Email draft created after approval (never sent)", "```text", (SAMPLE_DIR / "support_reply_draft.txt").read_text(encoding="utf-8").strip(),
        "```", "The `.eml` version (`X-Unsent: 1`) is in `outputs/evidence/sample_mcp/`."]
(EV / "sample_outputs.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print("wrote", EV / "sample_outputs.md")
